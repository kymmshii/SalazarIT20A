
package PRELIM;


public class multiArray {
     public static void main(String[] args) {
    int age [][] = {
        {10, 71, 41},
        {15, 16, 20},
        {45, 48, 60},
};
    for (int i = 0; i < age.length; i++){
    for (int j= 0; j < age[i].length; j++){
        System.out.print(age[i][j] + " ");
    }
    System.out.println();
}
    
     }
}
    

